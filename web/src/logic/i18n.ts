export const TEXT: { en: Record<Key, string>; tr: Record<Key, string> } = { en, tr };

let lang: Lang = 'en';

export function getLang(): Lang { return lang; }

export function setLang(l: Lang): void {
  lang = l;
  if (typeof document !== 'undefined') document.documentElement.lang = l;
}

/** The current language's text; '{name}' takes String(params.name), a hole with no param stays as is. */
export function t(key: Key, params?: Record<string, string | number>): string {
  return TEXT[lang][key].replace(/\{(\w+)\}/g, (hole, name: string) => params && name in params ? String(params[name]) : hole);
}

/** A wait reason in the current language; notification and note text is shown as it came. */
export function reasonText(r: Reason): string {
  return r.kind === 'permission' ? t('reason.permission', { what: toolName(r.tool) + (r.label ? ' ' + r.label : '') }) : r.kind === 'question' ? t('reason.question') : r.text;
}

/** All of an agent's wait reasons on one line, '' when none. */
export function whyText(a: AgentView): string {
  return a.reasons.map(reasonText).join(' · ');
}
